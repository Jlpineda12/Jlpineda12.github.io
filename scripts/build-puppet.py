"""Builds the vector puppet sprite from character-src/*.svg (José's own layers from Personaje.psd).

Usage: python3 scripts/build-puppet.py
Writes src/components/PuppetSprite.astro: one hidden <svg> with every part as a <g id="pp-…">,
placed in the original 1668×2388 canvas. Puppet.astro then draws a character with <use> links,
so the page carries the artwork once no matter how many times José appears.
"""
import json
import re
from pathlib import Path

SRC = Path('character-src')
OUT = Path('src/components/PuppetSprite.astro')
manifest = json.loads((SRC / 'manifest.json').read_text())

num = re.compile(r'-?\d+\.\d+')


def compact(d):
    # Whole numbers are plenty: the canvas is 1668 units wide and José is never drawn bigger than
    # about 500px, so rounding moves a point by less than half a pixel and halves the page weight.
    d = num.sub(lambda m: str(round(float(m.group()))), d)
    d = re.sub(r'(?<![\d.])-0(?![\d.])', '0', d)
    # Drop points repeated back to back ("C1 2 1 2 1 2" style no-ops are kept; only spacing is cleaned).
    return re.sub(r'\s+', ' ', d).strip()


def part(file, pid):
    svg = (SRC / file).read_text()
    x, y, *_ = map(float, re.search(r'viewSource="([^"]+)"', svg).group(1).split())
    paths = re.findall(r'<path\b[^>]*/>', svg)
    out = []
    for p in paths:
        style = re.search(r'style="([^"]*)"', p)
        d = re.search(r'\sd="([^"]*)"', p)
        if not d:
            continue
        fill = re.search(r'fill:\s*(#[0-9A-Fa-f]{3,8}|none)', style.group(1) if style else '')
        fop = re.search(r'fill-opacity:\s*([\d.]+)', style.group(1) if style else '')
        attrs = f' fill="{fill.group(1)}"' if fill else ''
        if fop and float(fop.group(1)) < 1:
            attrs += f' fill-opacity="{fop.group(1)}"'
        out.append(f'<path{attrs} d="{compact(d.group(1))}"/>')
    return f'<g id="{pid}" transform="translate({x:.1f} {y:.1f})">{"".join(out)}</g>'


groups = []
for name in ['neck', 'shirt', 'neck-shadow', 'ears', 'ear-shade', 'face', 'hair', 'nose', 'glasses']:
    groups.append(part(manifest[name]['file'], f'pp-{name}'))
for name, keep in [('lenses', None), ('pupils', None), ('mouth', None), ('hands', [0]), ('headphones', [0])]:
    frames = manifest[name]['frames']
    for k, f in enumerate(frames):
        if keep is not None and k not in keep:
            continue
        groups.append(part(f['file'], f'pp-{name}-{k}'))

# Closed eyes (sleep and the middle of a blink). In José's frames the lid drops from the top,
# so the eye shuts along the bottom of the lens: a thick soft curve low in each lens.
closed = []
for cx, bottom in ((685, 1272), (987, 1269)):
    closed.append(f'<path d="M{cx - 62} {bottom - 46} Q{cx} {bottom - 6} {cx + 62} {bottom - 46}" fill="none" stroke="#363636" stroke-width="16" stroke-linecap="round"/>')
groups.append(f'<g id="pp-closed">{"".join(closed)}</g>')

body = '\n    '.join(groups)
# One clip per lid position, so the pupil always sits behind the current eyelid.
# (a clipPath can't point at a <g>, so each clip carries the lens paths themselves)
def clip_paths(k):
    g = part(manifest['lenses']['frames'][k]['file'], 'x')
    tr = re.search(r'transform="([^"]+)"', g).group(1)
    return ''.join(p.replace('<path', f'<path transform="{tr}"', 1) for p in re.findall(r'<path[^>]*/>', g))
clips = '\n    '.join(f'<clipPath id="pp-lens-clip-{k}">{clip_paths(k)}</clipPath>' for k in range(6))
astro = f'''---
// Generated by scripts/build-puppet.py from character-src (José's vector layers). Do not edit by hand.
---
<svg class="pp-sprite" aria-hidden="true" focusable="false" width="0" height="0">
  <defs>
    {body}
    {clips}
  </defs>
</svg>

<style>
  .pp-sprite {{
    position: absolute;
    width: 0;
    height: 0;
    overflow: hidden;
  }}
</style>
'''
OUT.write_text(astro)
print(OUT, f'{OUT.stat().st_size / 1024:.0f} KB', len(groups), 'parts')
