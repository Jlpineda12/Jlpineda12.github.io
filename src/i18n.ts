// Languages: Spanish lives at /, English at /en/. Components take a `lang` prop and read
// their data with getData(lang) and their interface words with t(lang).
import * as es from './data/site';
import { enSite, enProjects, enWorlds, enProcess, enSoftSkills, enStudioSpots, enTools, enLanguages } from './data/en';

export type Lang = 'es' | 'en';

export function getData(lang: Lang) {
  if (lang === 'es') return es;
  return {
    ...es,
    site: { ...es.site, ...enSite },
    projects: es.projects.map((p) => ({ ...p, ...(enProjects[p.slug] ?? {}) })),
    worlds: es.worlds.map((w) => ({ ...w, ...(enWorlds[w.id] ?? {}) })),
    process: es.process.map((s) => ({ ...s, ...(enProcess[s.island] ?? {}) })),
    softSkills: enSoftSkills,
    studioSpots: es.studioSpots.map((s, i) => ({ ...s, ...enStudioSpots[i] })),
    tools: es.tools.map((t) => enTools[t.group] ?? t),
    languages: es.languages.map((l) => enLanguages[l.group] ?? l),
  };
}

